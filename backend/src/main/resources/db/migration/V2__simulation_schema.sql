-- Simulated LMS tables used only by the simulation package (not the focus of the assessment).

CREATE TABLE course (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code   VARCHAR(20)  NOT NULL,
    title  VARCHAR(150) NOT NULL,
    status VARCHAR(16)  NOT NULL,
    CONSTRAINT pk_course PRIMARY KEY (id),
    CONSTRAINT uq_course_code UNIQUE (code),
    CONSTRAINT ck_course_status CHECK (status IN ('OPEN','CLOSED'))
);

CREATE TABLE student (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    student_number VARCHAR(20)  NOT NULL,
    first_name     VARCHAR(60)  NOT NULL,
    last_name      VARCHAR(60)  NOT NULL,
    email          VARCHAR(150) NOT NULL,
    CONSTRAINT pk_student PRIMARY KEY (id),
    CONSTRAINT uq_student_number UNIQUE (student_number),
    CONSTRAINT uq_student_email UNIQUE (email)
);

CREATE TABLE enrollment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    course_id      BIGINT       NOT NULL,
    student_id     BIGINT       NOT NULL,
    score          DECIMAL(5,2),
    letter_grade   VARCHAR(2),
    completed      BOOLEAN      NOT NULL DEFAULT FALSE,
    last_graded_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_enrollment PRIMARY KEY (id),
    CONSTRAINT fk_enrollment_course  FOREIGN KEY (course_id)  REFERENCES course (id),
    CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id) REFERENCES student (id),
    CONSTRAINT uq_enrollment UNIQUE (course_id, student_id),
    CONSTRAINT ck_enrollment_score CHECK (score IS NULL OR (score >= 0 AND score <= 100))
);

CREATE TABLE award (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    enrollment_id BIGINT       NOT NULL,
    award_type    VARCHAR(16)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    awarded_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    job_id        UUID         NOT NULL,
    CONSTRAINT pk_award PRIMARY KEY (id),
    CONSTRAINT fk_award_enrollment FOREIGN KEY (enrollment_id) REFERENCES enrollment (id),
    CONSTRAINT fk_award_job FOREIGN KEY (job_id) REFERENCES job (id),
    CONSTRAINT uq_award UNIQUE (enrollment_id, award_type, name),
    CONSTRAINT ck_award_type CHECK (award_type IN ('BADGE','CERTIFICATE'))
);

CREATE TABLE term (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code         VARCHAR(10) NOT NULL,
    name         VARCHAR(60) NOT NULL,
    status       VARCHAR(16) NOT NULL,
    fee_due_date DATE        NOT NULL,
    CONSTRAINT pk_term PRIMARY KEY (id),
    CONSTRAINT uq_term_code UNIQUE (code),
    CONSTRAINT ck_term_status CHECK (status IN ('OPEN','CLOSED'))
);

CREATE TABLE student_account (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    student_id       BIGINT        NOT NULL,
    term_id          BIGINT        NOT NULL,
    tuition_amount   DECIMAL(10,2) NOT NULL,
    aid_amount       DECIMAL(10,2) NOT NULL DEFAULT 0,
    amount_paid      DECIMAL(10,2) NOT NULL DEFAULT 0,
    balance          DECIMAL(10,2) NOT NULL DEFAULT 0,
    aid_status       VARCHAR(16)   NOT NULL,
    last_assessed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_student_account PRIMARY KEY (id),
    CONSTRAINT fk_account_student FOREIGN KEY (student_id) REFERENCES student (id),
    CONSTRAINT fk_account_term    FOREIGN KEY (term_id)    REFERENCES term (id),
    CONSTRAINT uq_account UNIQUE (student_id, term_id),
    CONSTRAINT ck_account_aid_status CHECK (aid_status IN ('ELIGIBLE','INELIGIBLE','PENDING_REVIEW')),
    CONSTRAINT ck_account_amounts CHECK (tuition_amount >= 0 AND aid_amount >= 0 AND amount_paid >= 0)
);

CREATE TABLE account_charge (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id  BIGINT        NOT NULL,
    charge_type VARCHAR(16)   NOT NULL,
    amount      DECIMAL(10,2) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    job_id      UUID          NOT NULL,
    CONSTRAINT pk_account_charge PRIMARY KEY (id),
    CONSTRAINT fk_charge_account FOREIGN KEY (account_id) REFERENCES student_account (id),
    CONSTRAINT fk_charge_job     FOREIGN KEY (job_id)     REFERENCES job (id),
    CONSTRAINT uq_charge UNIQUE (account_id, charge_type),
    CONSTRAINT ck_charge_type CHECK (charge_type IN ('LATE_FEE')),
    CONSTRAINT ck_charge_amount CHECK (amount > 0)
);

CREATE TABLE notification_template (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code    VARCHAR(40)   NOT NULL,
    kind    VARCHAR(20)   NOT NULL,
    subject VARCHAR(150)  NOT NULL,
    body    VARCHAR(2000) NOT NULL,
    active  BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_notification_template PRIMARY KEY (id),
    CONSTRAINT uq_template_code UNIQUE (code),
    CONSTRAINT ck_template_kind CHECK (kind IN ('FORUM_POST','ANNOUNCEMENT','DIRECT_MESSAGE'))
);

CREATE TABLE notification_delivery (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id     UUID       NOT NULL,
    student_id BIGINT     NOT NULL,
    channel    VARCHAR(8) NOT NULL,
    status     VARCHAR(8) NOT NULL,   -- idempotency flag
    sent_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_notification_delivery PRIMARY KEY (id),
    CONSTRAINT fk_delivery_job     FOREIGN KEY (job_id)     REFERENCES job (id),
    CONSTRAINT fk_delivery_student FOREIGN KEY (student_id) REFERENCES student (id),
    CONSTRAINT uq_delivery UNIQUE (job_id, student_id),
    CONSTRAINT ck_delivery_channel CHECK (channel IN ('EMAIL','PUSH')),
    CONSTRAINT ck_delivery_status  CHECK (status IN ('PENDING','SENT')),
    CONSTRAINT ck_delivery_sent_at CHECK (status = 'PENDING' OR sent_at IS NOT NULL)
);
