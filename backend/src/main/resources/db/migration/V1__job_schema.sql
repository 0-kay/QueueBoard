-- The job queue: one row per job, one row per attempt. This is the assessment core.

CREATE TABLE job (
    id              UUID                      NOT NULL,
    name            VARCHAR(100)              NOT NULL,
    type            VARCHAR(32)               NOT NULL,
    status          VARCHAR(16)               NOT NULL,
    payload         VARCHAR(4000)             NOT NULL,  -- validated JSON
    attempts        INT                       NOT NULL DEFAULT 0,
    max_attempts    INT                       NOT NULL DEFAULT 3,
    result_summary  VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE  NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE  NOT NULL,
    deleted_at      TIMESTAMP WITH TIME ZONE,              -- soft delete
    version         BIGINT                    NOT NULL DEFAULT 0,
    CONSTRAINT pk_job PRIMARY KEY (id),
    CONSTRAINT ck_job_type   CHECK (type IN ('GRADE_REPORT','NOTIFICATION_BATCH','BILLING_ASSESSMENT')),
    CONSTRAINT ck_job_status CHECK (status IN ('QUEUED','PROCESSING','COMPLETED','FAILED')),
    CONSTRAINT ck_job_attempts CHECK (attempts >= 0 AND attempts <= max_attempts)
);
CREATE INDEX ix_job_status_created ON job (status, created_at);
CREATE INDEX ix_job_type ON job (type);

CREATE TABLE job_attempt (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id          UUID                      NOT NULL,
    attempt_number  INT                       NOT NULL,
    started_at      TIMESTAMP WITH TIME ZONE  NOT NULL,
    finished_at     TIMESTAMP WITH TIME ZONE,
    outcome         VARCHAR(16),               -- null while running
    error_code      VARCHAR(40),               -- JobErrorCode name
    error_message   VARCHAR(1000),
    CONSTRAINT pk_job_attempt PRIMARY KEY (id),
    CONSTRAINT fk_job_attempt_job FOREIGN KEY (job_id) REFERENCES job (id),
    CONSTRAINT uq_job_attempt UNIQUE (job_id, attempt_number),
    CONSTRAINT ck_job_attempt_outcome CHECK (outcome IS NULL OR outcome IN ('COMPLETED','FAILED'))
);
